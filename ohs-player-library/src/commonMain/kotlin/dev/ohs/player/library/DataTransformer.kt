package dev.ohs.player.library

import dev.ohs.fhir.fhirpath.FhirPathEngine
import dev.ohs.fhir.model.r4.Resource
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.decodeFromJsonElement
/**
 * Transforms a FHIR resource into a generated Kotlin type T.
 * Uses the OHS Kotlin FHIR SDK's FhirPathEngine for evaluation.
 */
class DataTransformer(
    private val fhirPathEngine: FhirPathEngine,
    @PublishedApi
    internal val jsonConfiguration: Json = Json {
        ignoreUnknownKeys = true
        coerceInputValues = true
    }
) {

    /**
     * Transforms a FHIR resource into the generated Kotlin type T.
     * T is the class generated by KotlinPoet (e.g. PatientHeaderState).
     */
    inline fun <reified T : Any> transform(request: FhirExtractionRequest): T {
        val jsonObject = extractToJson(request)
        return jsonConfiguration.decodeFromJsonElement<T>(jsonObject)
    }

    /**
     * Extracts fields from a FHIR resource based on the paths map in
     * FhirExtractionRequest. Returns a flat JsonObject of name → value.
     */
    fun extractToJson(request: FhirExtractionRequest): JsonObject {
        val resultFields = mutableMapOf<String, JsonElement>()
        request.paths.forEach { (name, path) ->
            val value = evaluatePath(request.resource, path, request.context)
            resultFields[name] = value.toJsonElement()
        }
        return JsonObject(resultFields)
    }

    private fun evaluatePath(focus: Any?, path: String, context: List<Resource>): String? {
        return try {
            val variables = if (context.isNotEmpty()) mapOf("context" to context) else emptyMap()
            val results: Collection<Any> = fhirPathEngine.evaluateExpression(
                expression = path,
                base = focus,
                variables = variables
            )
            results.firstOrNull()?.toString()
        } catch (e: Exception) {
            null
        }
    }

    private fun String?.toJsonElement(): JsonElement =
        if (this == null) JsonNull else JsonPrimitive(this)

    companion object {
        fun forR4(): DataTransformer = DataTransformer(FhirPathEngine.forR4())
    }
}