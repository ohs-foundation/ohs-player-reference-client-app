package dev.ohs.player.library.tranformer

import dev.ohs.fhir.fhirpath.FhirPathEngine
import dev.ohs.fhir.model.r4.Resource
import dev.ohs.player.library.config.ViewDefinition
import kotlinx.serialization.json.*

/**
 * The Typed DataTransformer adapted for OHS Kotlin FHIR SDK.
 * Uses the specific evaluateExpression signature for FHIRPath evaluation.
 */
class DataTransformer(
    private val fhirPathEngine: FhirPathEngine,
    private val jsonConfiguration: Json = Json {
        ignoreUnknownKeys = true
        coerceInputValues = true
    }
) {

    /**
     * Transforms a FHIR resource into the generated Kotlin Type T.
     * T is the class generated by KotlinPoet (e.g., PatientHeaderState).
     */
    internal inline fun <reified T : Any> transform(
        resource: Resource,
        viewDef: ViewDefinition,
        context: List<Resource> = emptyList()
    ): T {
        val jsonObject = extractToJson(resource, viewDef, context)
        return jsonConfiguration.decodeFromJsonElement<T>(jsonObject)
    }

    /**
     * Extracts data based on the 'select.column' structure of your ViewDefinition.
     */
    fun extractToJson(
        resource: Resource,
        viewDef: ViewDefinition,
        context: List<Resource>
    ): JsonObject {
        val resultFields = mutableMapOf<String, JsonElement>()
        // Flatten all select blocks and process each column
        viewDef.allColumns().forEach { column ->
            val value = evaluatePath(resource, column.path, context)
            resultFields[column.name] = value.toJsonElement()
        }
        return JsonObject(resultFields)
    }

    /**
     * Uses the OHS-specific evaluateExpression signature.
     */
    private fun evaluatePath(focus: Any?, path: String, context: List<Resource>): String? {
        return try {
            // Mapping context resources to a variable map for use within FHIRPath if needed
            val variables = if (context.isNotEmpty()) mapOf("context" to context) else emptyMap()

            // Signature: evaluateExpression(expression, base, variables)
            val results: Collection<Any> = fhirPathEngine.evaluateExpression(
                expression = path,
                base = focus,
                variables = variables
            )

            results.firstOrNull()?.let { result ->
                // result.toString() extracts the primitive value or string representation
                // from the Kotlin FHIR model object.
                result.toString()
            }
        } catch (e: Exception) {
            // Ensure runtime FHIRPath errors don't break the transformation flow
            null
        }
    }

    private fun String?.toJsonElement(): JsonElement {
        return if (this == null) JsonNull else JsonPrimitive(this)
    }
}